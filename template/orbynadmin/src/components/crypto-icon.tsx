/**
 * Inline brand marks for the crypto dashboard. Flat circular icons in the
 * style of theSVG / cryptocurrency-icons. Self-contained (no network
 * requests), so they render instantly and work offline.
 */

type Props = { symbol: string; size?: number; className?: string };

function Cardano() {
  // Dark-blue disc with a constellation of white dots.
  const inner = 5.1;
  const outer = 8.8;
  // Round to a fixed precision so the server and client serialize identical
  // coordinate strings (avoids a float-precision hydration mismatch).
  const round = (n: number) => Math.round(n * 1000) / 1000;
  const ring = (r: number, dr: number, start = 0) =>
    Array.from({ length: 6 }, (_, i) => {
      const a = ((start + i * 60) * Math.PI) / 180;
      return (
        <circle
          key={`${r}-${i}`}
          cx={round(16 + r * Math.cos(a))}
          cy={round(16 + r * Math.sin(a))}
          r={dr}
          fill="#fff"
        />
      );
    });
  return (
    <>
      <circle cx="16" cy="16" r="16" fill="#0033AD" />
      <circle cx="16" cy="16" r="1.7" fill="#fff" />
      {ring(inner, 1.3, 0)}
      {ring(outer, 1, 30)}
    </>
  );
}

